import { DatabaseSync } from 'node:sqlite';
import { mkdirSync, chmodSync, readFileSync, writeFileSync } from 'node:fs';
import { randomBytes, randomUUID, createHash } from 'node:crypto';
import path from 'node:path';
import { config } from './config.mjs';
mkdirSync(config.data, { recursive: true, mode: 0o700 });
export const db = new DatabaseSync(path.join(config.data, 'sterio.sqlite'));
db.exec(`PRAGMA journal_mode=WAL; PRAGMA busy_timeout=5000;
CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS devices (id TEXT PRIMARY KEY, name TEXT NOT NULL, public_key TEXT NOT NULL, created INTEGER NOT NULL, revoked INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS sessions (hash TEXT PRIMARY KEY, device_id TEXT NOT NULL, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS tracks (id TEXT PRIMARY KEY, path TEXT UNIQUE NOT NULL, size INTEGER NOT NULL, mtime REAL NOT NULL, metadata TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS cue_tracks (id TEXT PRIMARY KEY, cue_path TEXT NOT NULL, source_id TEXT NOT NULL, metadata TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS split_sets (folder TEXT PRIMARY KEY, source_path TEXT NOT NULL, metadata TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS device_admins (device_id TEXT PRIMARY KEY);
CREATE TABLE IF NOT EXISTS favorites (device_id TEXT NOT NULL, item_id TEXT NOT NULL, PRIMARY KEY(device_id,item_id));
CREATE TABLE IF NOT EXISTS radio_likes (device_id TEXT NOT NULL, song_id TEXT NOT NULL, title TEXT NOT NULL, artist TEXT NOT NULL, album TEXT NOT NULL, liked_at INTEGER NOT NULL, PRIMARY KEY(device_id,song_id));
CREATE TABLE IF NOT EXISTS progress (device_id TEXT PRIMARY KEY, track_id TEXT NOT NULL, position REAL NOT NULL, updated INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS peers (id TEXT PRIMARY KEY, url TEXT NOT NULL, name TEXT NOT NULL, created INTEGER NOT NULL, revision TEXT NOT NULL DEFAULT '', synced INTEGER, error TEXT NOT NULL DEFAULT '');
CREATE TABLE IF NOT EXISTS peer_tracks (peer_id TEXT NOT NULL, remote_id TEXT NOT NULL, metadata TEXT NOT NULL, PRIMARY KEY(peer_id,remote_id));
CREATE TABLE IF NOT EXISTS peer_media (id TEXT PRIMARY KEY, peer_id TEXT NOT NULL, track_id TEXT NOT NULL, remote_id TEXT NOT NULL, path TEXT NOT NULL, request TEXT NOT NULL, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS peer_clients (device_id TEXT PRIMARY KEY, server_id TEXT NOT NULL, name TEXT NOT NULL, created INTEGER NOT NULL);
`);
chmodSync(path.join(config.data, 'sterio.sqlite'), 0o600);
export const hash = value => createHash('sha256').update(value).digest('hex');
export const getSetting = key => db.prepare('SELECT value FROM settings WHERE key=?').get(key)?.value;
export const setSetting = (key, value) => db.prepare('INSERT INTO settings VALUES (?,?) ON CONFLICT(key) DO UPDATE SET value=excluded.value').run(key, String(value));
if (!getSetting('serverId')) setSetting('serverId', randomUUID());
export const serverId = getSetting('serverId');
const secretPath = path.join(config.data, 'ticket-secret');
try { writeFileSync(secretPath, randomBytes(32), { flag: 'wx', mode: 0o600 }); } catch (error) { if (error.code !== 'EEXIST') throw error; }
export const ticketSecret = readFileSync(secretPath);
if (ticketSecret.length !== 32) throw new Error('Invalid ticket secret in data volume');
